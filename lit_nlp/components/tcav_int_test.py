def _unit_scale_cav(result):
  """Normalizes the trained CAV and dot products to unit CAV scale.

  The magnitude of scikit-learn LinearSVC coefficients (and hence the CAV)
  varies across library versions without changing the CAV direction, which is
  what TCAV scores depend on. Normalizing keeps the golden values stable
  across scikit-learn upgrades.
  """
  result = dict(result)
  inner = dict(result['result'])
  cav = np.asarray(inner['cav'], dtype=np.float64)
  scale = np.linalg.norm(cav)
  inner['cav'] = (cav / scale).tolist()
  inner['dot_prods'] = [d / scale for d in inner['dot_prods']]
  result['result'] = inner
  return result


